import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import { compileScript, compileTemplate, parse } from '@vue/compiler-sfc'
const read = (file) => readFileSync(new URL(file,import.meta.url),'utf8')
const source = read('./ComposeTaskCreateDialog.vue')
describe('manual task batch creation', () => {
  it('compiles creation, material selection, inherited settings and batch detail components', () => {
    for(const file of ['./ComposeTaskCreateDialog.vue','./ComposeTaskMaterialSelector.vue','./ComposeTaskSettings.vue','./ComposeTaskBatchDetail.vue','./ComposeStrategyPicker.vue']) {
      const parsed=parse(read(file),{filename:file})
      expect(parsed.errors).toEqual([])
      expect(compileTemplate({source:parsed.descriptor.template.content,filename:file,id:file}).errors).toEqual([])
      expect(()=>compileScript(parsed.descriptor,{id:file})).not.toThrow()
    }
  })
  it('queries exact assignment remotely and uses the selected strategy detail for full inherited settings', () => {
    expect(source).not.toContain('client.listStrategies()')
    expect(source).toContain("{team_id:teamID,category_id:categoryID,operator_id:operatorID,status:'enabled'}")
    expect(source).toContain('@detail="strategyDetail=$event"')
    expect(source).toContain('sourceSeed.value.strategy : strategyDetail.value')
    const picker=read('./ComposeStrategyPicker.vue')
    expect(picker).toContain('@search="search"')
    expect(picker).toContain('remote @search')
    const select=read('../../../shared/ui/fields/BusinessSelect.vue')
    expect(select).toContain('remote: Boolean')
    expect(select).toContain(':filter="remote ? () => true : undefined"')
    expect(picker).toContain('directory.more()')
    expect(picker).toContain('directory.resolve(id)')
  })
  it('requires task name before assignment and selection, and confirms invalidating context changes', () => {
    const template=source.slice(source.indexOf('<template>'))
    expect(template.indexOf('任务名称')).toBeLessThan(template.indexOf('所属类目'))
    expect(source).toContain("if(!name) {nameError.value='请输入任务名称';return}")
    expect(source).toContain('DialogPlugin.confirm')
    expect(source).toContain("changeContext('operator',$event)")
  })
  it('submits one idempotent batch with explicit owner, groups, and confirmed remake', () => {
    expect(source).toContain('body.request_key=submitted.value.key')
    expect(source).toContain('submitted.value.signature!==signature')
    expect(source).toContain('operator_id:operatorID.value')
    expect(source).toContain('setting_overrides:groupOverridePayload')
    expect(source).toContain('remake_confirmed:remakeConfirmed.value')
    expect(source).not.toContain('listStrategyMaterialStates')
  })
  it('keeps inherited group structure immutable while exposing only template-opened parameters', () => {
    const settings=read('./ComposeTaskSettings.vue')
    expect(settings).toContain("field.editable === true && field.key !== 'guide_video_url'")
    expect(settings).toContain(':disabled="!editable(field)"')
    for(const action of ['新增成片设置','拖动排序','复制','移除']) expect(settings).not.toContain(`>${action}<`)
    expect(settings).toContain('validateTaskGroup')
  })
  it('seeds source mode from the original output with a locked material and source-only submit', () => {
    expect(source).toContain('sourceOutput: Object')
    expect(source).toContain('outputRemakeSeed(props.sourceOutput, templates.value)')
    expect(source).toContain('isSource.value ? sourceSeed.value.strategy')
    expect(source).toContain('isSource.value ? outputRemakeBody(props.sourceOutput,name,sourceSeed.value,overrides.value)')
    expect(source).toContain('<ComposeTaskMaterialSelector v-if="!isSource"')
    expect(source).toContain('沿用原素材、原模板版本与原成片设置')
  })
  it('uses owner-context server queries without local file or video status filters', () => {
    const selector=read('./ComposeTaskMaterialSelector.vue')
    expect(selector).toContain('client.listMyMaterials(params) : client.list(params)')
    expect(selector).toContain('strategy_id: props.context.strategy_id')
    expect(selector).toContain('operator_id: props.context.operator_id')
    expect(selector).toContain('publishedRangeParams(filters.value.published)')
    expect(selector).toContain('metricLabel(row,')
    expect(selector).not.toContain('download_status')
    expect(selector).not.toContain('video_status')
    expect(selector).not.toContain('listStrategyMaterialStates')
  })
  it('writes selection only from confirmation and reports item failures before closing', () => {
    const selector=read('./ComposeTaskMaterialSelector.vue')
    const load=selector.slice(selector.indexOf('async function load()'),selector.indexOf('function query()'))
    expect(load).not.toContain('addUsage')
    expect(selector).toContain('acceptSelectedMaterials(selectedRows.value')
    expect(selector).toContain('client.addUsage(id, { strategy_id: props.context.strategy_id, operator_id: props.context.operator_id })')
    expect(selector).toContain('failures.value = result.failed')
    expect(selector).toContain("if (result.accepted.length) emit('selected', result.accepted)")
  })
})
