import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'

const read = (name) => readFileSync(new URL(`./${name}`, import.meta.url), 'utf8')

describe('discovery strategy and task pages', () => {
  it('presents strategies as rules with business language and stat cards', () => {
    const source = read('DiscoveryStrategiesPage.vue')
    expect(source).toContain('strategy_type')
    expect(source).toContain('关键词')
    expect(source).toContain('作者（维护中）')
    expect(source).toContain('value="author" disabled')
    expect(source).toContain("row.strategy_type === 'author'")
    expect(source).not.toContain('策略总数')
    expect(source).not.toContain('启用策略')
    expect(source).toContain('今日执行')
    expect(source).toContain('自动素材')
    expect(source).toContain('搜索策略名称')
    expect(source).toContain("colKey: 'id'")
    expect(source).toContain('required-mark')
    expect(source).toContain('执行方式')
    expect(source).toContain('执行周期')
    expect(source).toContain('配置说明')
    expect(source).toContain('规则类型')
    expect(source).toContain('判断方式')
    expect(source).not.toContain('判断条件')
    expect(source).toContain('策略状态')
    expect(source).toContain('所属游戏')
    expect(source).toContain('listGames')
    expect(source).toContain('gameName')
    expect(source).toContain('查询')
    expect(source).toContain('重置')
    expect(source).toContain('挖掘规则')
    expect(source).toContain('转素材规则')
    expect(source).toContain('最近效果')
    expect(source).toContain('latestStats')
    expect(source).toContain('materialRulesSummary')
    expect(source).toContain('material_rules')
    expect(source).toContain('resolveMaterialRules')
    expect(source).toContain('添加优先级')
    expect(source).toContain('<t-radio value="match">命中</t-radio>')
    expect(source).toContain('<t-radio value="filter">过滤</t-radio>')
    expect(source).not.toContain('value="AND"')
    expect(source).not.toContain('value="OR"')
    expect(source).not.toContain('label="自动转素材"')
    expect(source).not.toContain('v-model="form.config.like_threshold"')
    expect(source).not.toContain('v-model="form.config.favorite_threshold"')
    expect(source).toContain('openKeywords')
    expect(source).toContain('openAuthors')
    expect(source).toContain('KeywordTags')
    expect(source).toContain('strategy-rule-link')
    expect(source).toContain('t-dropdown')
    expect(source).toContain('更多')
    expect(source).toContain('updated_by_name')
    expect(source).toContain('关键词配置')
    expect(source).toContain('作者配置')
  })

  it('keeps strategy actions to five with run/edit/delete state control', () => {
    const source = read('DiscoveryStrategiesPage.vue')
    expect(source).toContain('详情')
    expect(source).toContain('openDetail')
    expect(source).toContain('策略详情')
    expect(source).toContain('created_by_name')
    expect(source).toContain('执行')
    expect(source).toContain('任务')
    expect(source).toContain('编辑')
    expect(source).toContain('复制')
    expect(source).toContain('删除')
    expect(source).toContain('deleteStrategy')
    expect(source).toContain('openCopy')
    expect(source).toContain('isRunning')
    expect(source).not.toContain('立即执行')
    expect(source).not.toContain('内容结果')
    expect(source).not.toContain('执行记录')
  })

  it('renders tasks with business naming, results, and a tabbed detail drawer', () => {
    const source = read('CrawlTasksPage.vue')
    expect(source).toContain('任务名称')
    expect(source).toContain('任务来源')
    expect(source).toContain('触发方式')
    expect(source).toContain("colKey: 'game'")
    expect(source).toContain('gameName(row.snapshot?.game_id)')
    expect(source).toContain('发现结果')
    expect(source).toContain('执行时间')
    expect(source).toContain('taskName')
    expect(source).toContain('sourceName')
    expect(source).toContain('sourceType')
    expect(source).toContain('查看策略')
    expect(source).toContain('triggerLabel')
    expect(source).toContain('foundStats')
    expect(source).toContain('详情')
    expect(source).toContain('重试')
    expect(source).toContain('结果概览')
    expect(source).toContain('发现内容')
    expect(source).toContain('执行过程')
    expect(source).toContain('异常记录')
    expect(source).toContain('timeline')
    expect(source).toContain('exceptions')
    expect(source).toContain('重新执行')
    expect(source).toContain('client.retryFailed')
    expect(source).toContain('待审核')
    expect(source).toContain('自动转素材')
    expect(source).toContain('执行中')
    expect(source).toContain('部分成功')
    expect(source).toContain('truncateTitle')
    expect(source).toContain('processing_status')
    expect(source).not.toContain('查看详情')
    expect(source).not.toContain('重试失败项')
    expect(source).not.toContain('策略快照')
    expect(source).not.toContain('关联原任务')
  })

  it('keeps strategy and task writes with senior operators while hiding them from operators', () => {
    const strategies = read('DiscoveryStrategiesPage.vue')
    expect(strategies).toContain("const canManage = computed(() => ['admin', 'senior_operator'].includes(currentUser.value?.role))")
    expect(strategies).toContain('v-if="canManage" theme="primary" @click="openCreate"')
    expect(strategies).toContain('v-if="canManage" size="small" theme="primary"')
    expect(strategies).toContain('v-if="canManage" size="small" class="wt-secondary-button" variant="outline" :disabled="isRunning(row)"')
    expect(strategies).toContain('v-if="canManage" trigger="click"')
    expect(strategies).toContain('if (!editingID.value && isAdmin.value && !form.value.team_id)')

    const tasks = read('CrawlTasksPage.vue')
    expect(tasks).toContain("const canManage = computed(() => ['admin', 'senior_operator'].includes(currentUser.value?.role))")
    expect(tasks).toContain('v-if="canManage && hasFailed(row)"')
    expect(tasks).toContain('v-if="canManage && detail && hasFailed(detail)"')
  })

  it('lets admins pick a team and shows the team column, using the full game catalog', () => {
    for (const page of ['DiscoveryStrategiesPage.vue', 'CrawlTasksPage.vue']) {
      const source = read(page)
      expect(source).toContain('createSessionClient')
      expect(source).toContain('const isAdmin = computed')
      expect(source).toContain('v-if="isAdmin"')
      expect(source).toContain('v-model="teamFilter"')
      expect(source).toContain("colKey: 'team'")
      expect(source).toContain('teamName(row.team_id)')
      expect(source).toContain("listGames({ scope: 'all' })")
    }
    const strategies = read('DiscoveryStrategiesPage.vue')
    expect(strategies).toContain('teamId: teamFilter.value || undefined')
    expect(strategies).toContain('v-if="isAdmin && !editingID" label="目标团队" required-mark')
    expect(strategies).toContain('if (!payload.team_id || editingID.value) delete payload.team_id')
    const tasks = read('CrawlTasksPage.vue')
    expect(tasks).toContain('team_id: teamFilter.value || undefined')
  })

  it('sends both discovery list filters to the backend instead of filtering locally', () => {
    const strategies = read('DiscoveryStrategiesPage.vue')
    expect(strategies).toContain('client.listStrategies(query)')
    expect(strategies).not.toContain('filteredRows')
    const tasks = read('CrawlTasksPage.vue')
    expect(tasks).toContain('client.listTasks(params)')
    expect(tasks).toContain('search: filters.value.search.trim()')
    expect(tasks).toContain('status: filters.value.status')
    expect(tasks).not.toContain('filteredRows')
  })

  it('paginates both discovery lists and keeps detail actions in drawer footers', () => {
    for (const page of ['DiscoveryStrategiesPage.vue', 'CrawlTasksPage.vue']) {
      const source = read(page)
      expect(source).toContain(':data="pagedRows"')
      expect(source).toContain(':total="rows.length"')
      expect(source).toContain('<t-pagination')
    }
    const tasks = read('CrawlTasksPage.vue')
    expect(tasks).toContain(':footer="Boolean(canManage && detail && hasFailed(detail))"')
    expect(tasks).toContain('<template #footer>')
    expect(tasks).toContain('@click="retry(detail)">重试</t-button>')
  })
})
