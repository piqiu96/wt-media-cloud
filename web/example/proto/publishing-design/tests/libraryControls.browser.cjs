const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { pathToFileURL } = require('node:url');
const root = process.env.PROTOTYPE_ROOT || path.resolve(__dirname, '..');
const evidence = process.env.SCREENSHOT_DIR || path.join(require('node:os').tmpdir(), 'wt-library-controls');
fs.mkdirSync(evidence, { recursive: true });
(async () => {
  const { seed } = await import(pathToFileURL(path.join(root, 'model.js')));
  const { createTemplate, publishDraft, setUsage } = await import(pathToFileURL(path.join(root, 'coverTemplates.js')));
  const data = seed();
  const legacy = { ...setUsage(publishDraft(createTemplate({ id: 9901, name: '曾设为默认的模板', size: '1080x1440', categories: [], platforms: [] }), ''), true), isDefault: true };
  const ordinary = { ...legacy, id: 9902, name: '普通已发布模板', isDefault: false };
  data.templates = [legacy, ordinary];
  let snapshot = { revision: 1, data }, fail = false, delay = 0;
  const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_EXECUTABLE ? { executablePath: process.env.CHROMIUM_EXECUTABLE } : {}) });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
    page.setDefaultTimeout(5000);
    const errors = [], passed = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.route('**/__example/publishing/**', async route => {
      const write = route.request().method() !== 'GET';
      if (write && delay) await new Promise(r => setTimeout(r, delay));
      if (write && fail) return route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ message: '走查模拟保存失败' }) });
      if (write) snapshot = { revision: snapshot.revision + 1, data: route.request().postDataJSON().data };
      return route.fulfill({ contentType: 'application/json', body: JSON.stringify(snapshot) });
    });
    const pass = name => { passed.push(name); console.log('PASS', name); };
    const name = data.images[0].name;
    const row = () => page.getByRole('row').filter({ has: page.getByText(name, { exact: true }) }).first();
    const control = () => row().getByRole('switch');
    const record = () => snapshot.data.images.find(i => i.id === data.images[0].id);
    const initial = !!data.images[0].enabled;
    const action = initial ? '停用' : '启用';
    const confirm = () => page.getByRole('button', { name: action, exact: true });
    await page.goto((process.env.PROTOTYPE_URL || (process.env.EXAMPLE_URL || 'http://127.0.0.1:8768') + '/example/?view=publishing') + '#images');
    await page.getByRole('heading', { name: '图片库', exact: true }).waitFor();
    await control().waitFor();
    assert.equal(await row().getByRole('button', { name: /^(启用|停用)$/ }).count(), 0);
    assert.equal(await control().getAttribute('aria-checked'), String(initial));
    pass('图片列表使用 Switch，操作列不重复放启停按钮');
    await control().click();
    await page.getByRole('button', { name: '取消', exact: true }).last().click();
    assert.equal(await control().getAttribute('aria-checked'), String(initial));
    assert.equal(record().enabled, initial);
    pass('取消启停保留原状态');
    fail = true;
    await control().click(); await confirm().click();
    await page.getByText('图片启停失败，原状态保持不变，请重试', { exact: true }).waitFor();
    assert.equal(await control().getAttribute('aria-checked'), String(initial));
    assert.equal(record().enabled, initial);
    pass('保存失败保留原状态并明确反馈');
    fail = false; delay = 650;
    await control().click(); await confirm().click();
    assert.equal(await control().getAttribute('aria-checked'), String(initial));
    assert.equal(await control().getAttribute('aria-disabled'), 'true');
    await page.waitForFunction(({name, expected}) => document.querySelector(`[role="switch"][aria-label="启用图片${name}"]`)?.getAttribute('aria-checked') === expected, { name, expected: String(!initial) });
    assert.equal(record().enabled, !initial);
    pass('保存期间保留原值并防重复，重试成功更新');
    delay = 0;
    await control().click();
    await page.getByRole('button', { name: initial ? '启用' : '停用', exact: true }).click();
    await page.waitForFunction(({name, expected}) => document.querySelector(`[role="switch"][aria-label="启用图片${name}"]`)?.getAttribute('aria-checked') === expected, { name, expected: String(initial) });
    await row().getByRole('button', { name: '编辑', exact: true }).click();
    const edit = page.getByRole('dialog');
    await edit.getByText('编辑图片', { exact: true }).waitFor();
    assert.equal(await edit.getByRole('switch').count(), 0);
    await edit.getByRole('button', { name: '取消', exact: true }).click();
    await page.reload(); await control().waitFor();
    assert.equal(await control().getAttribute('aria-checked'), String(initial));
    pass('连续切换、重载持久化正常；编辑弹窗没有第二个启停入口');
    await page.screenshot({ path: path.join(evidence, 'images-1440.png') });
    await page.setViewportSize({ width: 1280, height: 800 });
    await page.screenshot({ path: path.join(evidence, 'images-1280.png') });
    await page.goto((process.env.PROTOTYPE_URL || (process.env.EXAMPLE_URL || 'http://127.0.0.1:8768') + '/example/?view=publishing') + '#templates');
    await page.getByRole('heading', { name: '封面模板', exact: true }).waitFor();
    await page.getByText('普通已发布模板', { exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: /^(设为默认|默认模板)$/ }).count(), 0);
    assert.equal(await page.getByText('此规格默认模板', { exact: true }).count(), 0);
    assert.equal(await page.getByRole('switch').count(), 2);
    pass('模板库移除设为默认按钮和旧默认标记，保留正常启停');
    await page.screenshot({ path: path.join(evidence, 'templates-1280.png') });
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(evidence, 'results.json'), JSON.stringify({ passed, pageErrors: errors }, null, 2));
    console.log(`${passed.length} scenarios passed`);
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
