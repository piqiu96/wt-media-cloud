test('legacy planning metadata cannot hide started batches or mislabel cross-batch work', {timeout:30000}, async()=>{
 const {seed}=await import(source+'model.js');
 const {migrateRelationships}=await import(source+'relationships.js');
 const {migrateBatchLifecycle}=await import(source+'batchLifecycle.js');
 const {createBatchStore}=await import(source+'../../publishing-preview.mjs');
 const db=migrateRelationships(seed()),p=db.plans[0];
 const statuses=['排队中','排队中','执行中','结果待确认','结果待确认','平台审核中','已发布','执行失败','已取消','已放弃'];
 db.tasks.forEach((t,i)=>t.status=statuses[i]);migrateBatchLifecycle(db);
 assert.equal(p.control,'规划中');assert.equal(p.lockedAt,undefined);
 const state=()=>JSON.stringify({control:p.control,owner:p.owner,tasks:db.tasks.map(t=>[t.id,t.status,t.attempts])});
 const before=state(),store=createBatchStore();await store.bootstrap(db);
 const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_EXECUTABLE});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1050}});page.setDefaultTimeout(7000);
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/__example/publishing/**',async r=>{try{
   const q=r.request(),body=q.method()==='GET'?null:requestBody(q);
   const result=q.method()==='GET'?await store.get():q.url().endsWith('/command')?await store.command(body):await store.save(body.data,body.revision);
   await r.fulfill({json:result});
  }catch(e){await r.fulfill({status:409,json:{error:e.message}});}});
  await page.goto(base+'/example/operations/publishing/plans');
  const row=page.getByRole('row').filter({hasText:p.name});
  await row.getByText('进行中',{exact:true}).waitFor();
  await row.getByText('2 个批次有待处理任务',{exact:true}).waitFor();
  assert.equal(await page.getByText('本地保存失败',{exact:false}).count(),0);
  assert.equal(await row.getByText('待执行',{exact:true}).count(),0);
  await shot(page,'legacy-status-corrected.png');
  await row.getByRole('button',{name:'详情',exact:true}).click();
  await page.getByRole('button',{name:'查看待处理批次',exact:true}).click();
  await page.getByRole('heading',{name:'发布批次详情',exact:true}).waitFor();
  assert(page.url().includes('/batches/201'));
  const after=(await store.get()).data;
  assert.equal(after.plans[0].control,p.control);assert.equal(after.plans[0].owner,p.owner);
  assert.deepEqual(after.tasks.map(t=>[t.id,t.status,t.attempts]),db.tasks.map(t=>[t.id,t.status,t.attempts]));
  assert.equal(state(),before);assert.deepEqual(errors,[]);
 }finally{await browser.close();}
});
