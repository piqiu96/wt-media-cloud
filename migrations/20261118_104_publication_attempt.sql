CREATE TABLE publication_attempt (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 publication_id BIGINT UNSIGNED NOT NULL,
 attempt_no INT UNSIGNED NOT NULL,
 executor_user_id BIGINT UNSIGNED NOT NULL,
 browser_profile_id BIGINT UNSIGNED NOT NULL,
 claim_request_key VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
 input_snapshot_json JSON NOT NULL,
 status VARCHAR(24) NOT NULL,
 stage VARCHAR(32) NOT NULL,
 report_seq BIGINT UNSIGNED NOT NULL DEFAULT 0,
 started_at DATETIME(6) NOT NULL,
 heartbeat_at DATETIME(6) NOT NULL,
 submit_started_at DATETIME(6) NULL,
 finished_at DATETIME(6) NULL,
 result_status VARCHAR(24) NULL,
 error_code VARCHAR(64) NULL,
 error_message VARCHAR(1000) NULL,
 steps_json JSON NOT NULL,
 evidence_json JSON NOT NULL,
 result_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 resolved_by BIGINT UNSIGNED NULL,
 resolved_at DATETIME(6) NULL,
 resolution_note VARCHAR(2000) NULL,
 UNIQUE KEY uq_publication_attempt(publication_id,attempt_no),
 UNIQUE KEY uq_publication_claim(executor_user_id,claim_request_key),
 KEY idx_publication_heartbeat(status,heartbeat_at,id),
 KEY idx_publication_profile(browser_profile_id,status,id),
 CONSTRAINT fk_attempt_task FOREIGN KEY(publication_id) REFERENCES publication_task(id),
 CONSTRAINT fk_attempt_profile FOREIGN KEY(browser_profile_id) REFERENCES browser_profiles(id),
 CONSTRAINT chk_attempt_status CHECK(status IN ('running','awaiting_human','completed','interrupted'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
