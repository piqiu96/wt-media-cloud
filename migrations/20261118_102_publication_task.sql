ALTER TABLE operations_files ADD COLUMN delete_state VARCHAR(16) NOT NULL DEFAULT 'ready';

CREATE TABLE publication_task (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 team_id BIGINT UNSIGNED NOT NULL,
 operator_id BIGINT UNSIGNED NOT NULL,
 platform VARCHAR(32) NOT NULL,
 category_id BIGINT UNSIGNED NOT NULL,
 media_account_id BIGINT UNSIGNED NOT NULL,
 composite_output_id BIGINT UNSIGNED NOT NULL,
 platform_account_uid VARCHAR(255) COLLATE utf8mb4_bin NOT NULL,
 cover_file_id BIGINT NOT NULL,
 resource_snapshot_json JSON NOT NULL,
 content_json JSON NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'pending',
 current_attempt_id BIGINT UNSIGNED NULL,
 attempt_count INT UNSIGNED NOT NULL DEFAULT 0,
 not_before DATETIME(6) NULL,
 authorized_at DATETIME(6) NULL,
 revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
 created_by BIGINT UNSIGNED NOT NULL,
 request_key VARCHAR(64) COLLATE utf8mb4_bin NOT NULL,
 request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 occupied_output_id BIGINT UNSIGNED GENERATED ALWAYS AS (CASE WHEN status <> 'abandoned' THEN composite_output_id ELSE NULL END) STORED,
 executing_account_uid VARCHAR(255) COLLATE utf8mb4_bin GENERATED ALWAYS AS (CASE WHEN status IN ('running','awaiting_human','uncertain') THEN platform_account_uid ELSE NULL END) STORED,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 UNIQUE KEY uq_publication_output(platform,occupied_output_id),
 UNIQUE KEY uq_publication_uid(platform,executing_account_uid),
 UNIQUE KEY uq_publication_request(created_by,request_key),
 KEY idx_publication_owner(operator_id,status,not_before),
 KEY idx_publication_team(team_id,created_at),
 CONSTRAINT fk_publication_cover FOREIGN KEY(cover_file_id) REFERENCES operations_files(id),
 CONSTRAINT fk_publication_output FOREIGN KEY(composite_output_id) REFERENCES composite_outputs(id),
 CONSTRAINT fk_publication_account FOREIGN KEY(media_account_id) REFERENCES media_accounts(id),
 CONSTRAINT chk_publication_status CHECK(status IN ('pending','queued','running','awaiting_human','uncertain','reviewing','failed','published','cancelled','abandoned'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
